import { jsPDF } from "jspdf";

export type ProposalPdfInput = {
  title: string; content: string; clientName?: string; createdAt?: string;
  businessName?: string; businessAddress?: string; registrationNumber?: string | null;
  logoDataUrl?: string | null; showBranding?: boolean;
};

export function proposalFilename(title: string) {
  return `Proposal-${title.replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").slice(0, 100) || "document"}.pdf`;
}

export function generateProposalPdf(input: ProposalPdfInput): Blob {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const width = 515;
  let y = 44;
  const write = (text: string, size = 11, bold = false, indent = 0) => {
    doc.setFont("helvetica", bold ? "bold" : "normal"); doc.setFontSize(size); doc.setTextColor(30);
    const lines: string[] = doc.splitTextToSize(text.replace(/\*\*(.*?)\*\*/g, "$1").replace(/`([^`]+)`/g, "$1").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1"), width - indent);
    for (const line of lines) {
      if (y + size * 1.4 > 780) { doc.addPage(); y = 44; }
      doc.text(line, 40 + indent, y); y += size * 1.4;
    }
  };
  if (input.logoDataUrl) {
    try {
      const props = doc.getImageProperties(input.logoDataUrl);
      const ratio = props.width / props.height;
      const w = Math.min(100, 44 * ratio);
      doc.addImage(input.logoDataUrl, input.logoDataUrl.includes("jpeg") ? "JPEG" : "PNG", 40, y - 10, w, w / ratio);
      y += 54;
    } catch { /* missing logos do not block the document */ }
  }
  write(input.businessName || "Proposal", 16, true);
  if (input.businessAddress) write(input.businessAddress, 9);
  if (input.registrationNumber) write(`Registration: ${input.registrationNumber}`, 9);
  y += 18;
  write(input.title, 22, true); y += 8;
  if (input.clientName) write(`Prepared for: ${input.clientName}`, 10);
  if (input.createdAt) write(`Issued: ${new Date(input.createdAt).toLocaleDateString("en-ZA")}`, 10);
  y += 20;
  for (const raw of input.content.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) { y += 8; continue; }
    if (/^#\s/.test(line) && line.replace(/^#\s+/, "") === input.title) continue;
    const heading = line.match(/^(#{1,6})\s+(.+)$/);
    if (heading) { y += 10; if (y > 735) { doc.addPage(); y = 44; } write(heading[2], heading[1].length === 1 ? 18 : 14, true); y += 6; }
    else if (/^[-*+]\s+/.test(line)) { write(`• ${line.replace(/^[-*+]\s+/, "")}`, 11, false, 10); y += 4; }
    else if (/^\d+[.)]\s/.test(line)) { write(line, 11, false, 10); y += 4; }
    else if (/^\|?\s*:?-{3,}/.test(line)) continue;
    else { write(line.replace(/^\||\|$/g, "").replace(/\|/g, "  /  ")); y += 4; }
  }
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page); doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.setTextColor(110);
    if (input.showBranding !== false) doc.text("Generated by WinStream SA", 40, 816);
    doc.text(`${page} / ${pages}`, 555, 816, { align: "right" });
  }
  return doc.output("blob");
}